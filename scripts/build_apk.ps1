# Course Schedule - Android Release APK Automated Build Script
# Scoped strictly to process memory. Zero modification to global/machine environment.

[CmdletBinding()]
param(
    [switch]$SkipBuildAssets = $false
)

$ErrorActionPreference = "Stop"

Write-Host "========================================================" -ForegroundColor Cyan
Write-Host "  Course Schedule - Android APK Automated Build Pipeline" -ForegroundColor Cyan
Write-Host "========================================================" -ForegroundColor Cyan

# Path calculations
$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$projectRoot = (Resolve-Path "$scriptDir\..").Path
$clientDir = Join-Path $projectRoot "client"
$androidDir = Join-Path $clientDir "android"
$distDir = Join-Path $projectRoot "dist"
$targetApk = Join-Path $distDir "course_schedule_standalone.apk"

# ----------------------------------------------------
# Step 1: In-memory scoped environment variables
# ----------------------------------------------------
Write-Host "`n[1/5] Setting up in-memory process scoped environment..." -ForegroundColor Yellow

$jdkPath = $env:JAVA_HOME
if (-not $jdkPath) {
    $javaCommand = Get-Command java -ErrorAction SilentlyContinue
    if ($javaCommand) {
        $jdkPath = Split-Path -Parent (Split-Path -Parent $javaCommand.Source)
    } else {
        $candidates = @('C:\software', 'C:\Program Files\Java') | Where-Object { Test-Path -LiteralPath $_ } |
            ForEach-Object { Get-ChildItem -LiteralPath $_ -Directory -Filter 'jdk-*' -ErrorAction SilentlyContinue }
        $jdkPath = $candidates | Sort-Object Name -Descending | Select-Object -First 1 -ExpandProperty FullName
    }
}
$sdkPath = if ($env:ANDROID_HOME) { $env:ANDROID_HOME } elseif ($env:ANDROID_SDK_ROOT) { $env:ANDROID_SDK_ROOT } else { Join-Path $env:LOCALAPPDATA 'Android\Sdk' }

if (-not (Test-Path $jdkPath)) {
    throw "Fatal: JDK 17 not found at $jdkPath"
}
if (-not (Test-Path $sdkPath)) {
    throw "Fatal: Android SDK not found at $sdkPath"
}

$requiredSigning = @('COURSE_SIGNING_STORE_FILE', 'COURSE_SIGNING_STORE_PASSWORD', 'COURSE_SIGNING_KEY_ALIAS', 'COURSE_SIGNING_KEY_PASSWORD')
foreach ($name in $requiredSigning) {
    if (-not [Environment]::GetEnvironmentVariable($name, 'Process')) {
        throw "Release signing requires environment variable $name"
    }
}
if (-not (Test-Path -LiteralPath $env:COURSE_SIGNING_STORE_FILE)) {
    throw "Release signing keystore file not found"
}

# Strictly in-memory environment variables for current process only
$env:JAVA_HOME = $jdkPath
$env:ANDROID_HOME = $sdkPath
$env:ANDROID_SDK_ROOT = $sdkPath
$env:Path = "${env:JAVA_HOME}\bin;${env:ANDROID_HOME}\platform-tools;${env:Path}"

Write-Host "  [OK] JAVA_HOME    : $env:JAVA_HOME" -ForegroundColor DarkGray
Write-Host "  [OK] ANDROID_HOME : $env:ANDROID_HOME" -ForegroundColor DarkGray
Write-Host "  [OK] Process memory isolated - Registry/Global environment untouched" -ForegroundColor Green

# Ensure local.properties
$localPropPath = Join-Path $androidDir "local.properties"
$escapedSdk = $sdkPath.Replace('\', '\\')
Set-Content -Path $localPropPath -Value "## Auto-generated by build_apk.ps1`nsdk.dir=$escapedSdk`n" -Encoding UTF8
Write-Host "  [OK] local.properties configured" -ForegroundColor DarkGray

# ----------------------------------------------------
# Step 2: Native Wrapper and Capacitor Library dependencies
# ----------------------------------------------------
Write-Host "`n[2/5] Checking native Gradle Wrapper and Capacitor libraries..." -ForegroundColor Yellow

# Gradle wrapper check
if ((-not (Test-Path "$androidDir\gradlew.bat")) -or (-not (Test-Path "$androidDir\gradle\wrapper\gradle-wrapper.jar"))) {
    throw "Fatal: Local Gradle Wrapper not found in $androidDir"
}

# Capacitor Android module check
$capModuleDir = Join-Path $androidDir "capacitor-android"
if ((-not (Test-Path "$capModuleDir\src")) -or (-not (Test-Path "$capModuleDir\build.gradle"))) {
    throw "Fatal: Local Capacitor Android module not found in $capModuleDir"
}

Write-Host "  [OK] Android native scaffold and wrapper ready (100% self-contained)" -ForegroundColor Green

# ----------------------------------------------------
# Step 3: Anti-inflation check and Web Assets sync
# ----------------------------------------------------
Write-Host "`n[3/5] Syncing web assets and executing anti-inflation check..." -ForegroundColor Yellow

# Anti-inflation rule: NO APK permitted in client directory
$leakedApks = Get-ChildItem -Path $clientDir -Filter "*.apk" -Recurse -ErrorAction SilentlyContinue
if ($leakedApks) {
    foreach ($apk in $leakedApks) {
        Write-Host "  [WARNING] Detected APK in client dir: $($apk.FullName). Removing to prevent recursive inflation..." -ForegroundColor Red
        Remove-Item -Path $apk.FullName -Force
    }
}

$assetsPublic = Join-Path $androidDir "app\src\main\assets\public"
$assetsRoot = Join-Path $androidDir "app\src\main\assets"
New-Item -ItemType Directory -Force -Path $assetsPublic | Out-Null

# Sync index.html
Copy-Item -Path "$clientDir\index.html" -Destination "$assetsPublic\index.html" -Force

# Sync src directory
$targetSrc = Join-Path $assetsPublic "src"
if (Test-Path $targetSrc) {
    Remove-Item -Path $targetSrc -Recurse -Force
}
Copy-Item -Path "$clientDir\src" -Destination $targetSrc -Recurse -Force

# Sync capacitor.config.json
Copy-Item -Path "$clientDir\capacitor.config.json" -Destination "$assetsPublic\capacitor.config.json" -Force
Copy-Item -Path "$clientDir\capacitor.config.json" -Destination "$assetsRoot\capacitor.config.json" -Force

# Dummy cordova compatibility files
if (-not (Test-Path "$assetsPublic\cordova.js")) {
    New-Item -ItemType File -Path "$assetsPublic\cordova.js" -Force | Out-Null
}
if (-not (Test-Path "$assetsPublic\cordova_plugins.js")) {
    New-Item -ItemType File -Path "$assetsPublic\cordova_plugins.js" -Force | Out-Null
}

$syncedFiles = Get-ChildItem -Path $assetsPublic -Recurse -File
$syncedBytes = ($syncedFiles | Measure-Object -Property Length -Sum).Sum
$syncedKB = [math]::Round($syncedBytes / 1KB, 2)
Write-Host "  [OK] Synced $($syncedFiles.Count) frontend files ($syncedKB KB) to assets/public" -ForegroundColor Green

# ----------------------------------------------------
# Step 4: Run Gradle Release APK compilation
# ----------------------------------------------------
Write-Host "`n[4/5] Executing Gradle assembleRelease..." -ForegroundColor Yellow

Push-Location $androidDir
try {
    & .\gradlew.bat clean assembleRelease --no-daemon
    if ($LASTEXITCODE -ne 0) {
        throw "Gradle build failed with exit code: $LASTEXITCODE"
    }
} finally {
    Pop-Location
}

# Locate generated APK
$releaseApkSource = Join-Path $androidDir "app\build\outputs\apk\release\app-release.apk"
if (-not (Test-Path $releaseApkSource)) {
    $candidates = Get-ChildItem -Path "$androidDir\app\build\outputs\apk" -Filter "*.apk" -Recurse
    if ($candidates.Count -gt 0) {
        $releaseApkSource = $candidates[0].FullName
    } else {
        throw "Fatal: No APK file generated in build outputs!"
    }
}

# ----------------------------------------------------
# Step 5: Distribute to dist and Assert Size (<5MB)
# ----------------------------------------------------
Write-Host "`n[5/5] Distributing APK and asserting size constraints..." -ForegroundColor Yellow

if (-not (Test-Path $distDir)) {
    New-Item -ItemType Directory -Force -Path $distDir | Out-Null
}

Copy-Item -Path $releaseApkSource -Destination $targetApk -Force

if (-not (Test-Path $targetApk)) {
    throw "Fatal: Target APK failed to copy to: $targetApk"
}

$apkItem = Get-Item $targetApk
$apkBytes = $apkItem.Length
$apkMB = [math]::Round($apkBytes / 1MB, 2)

Write-Host "========================================================" -ForegroundColor Green
Write-Host "  SUCCESS: Android Release APK built successfully!" -ForegroundColor Green
Write-Host "  Output path : $targetApk" -ForegroundColor Green
Write-Host "  Exact size  : $apkMB MB ($apkBytes bytes)" -ForegroundColor Green
Write-Host "========================================================" -ForegroundColor Green

if ($apkBytes -ge 5 * 1024 * 1024) {
    throw "Quality Violation: APK size ($apkMB MB) exceeds 5.0 MB maximum constraint!"
} else {
    Write-Host "  [OK] Acceptance Criteria 5 Met: APK size strictly < 5.0 MB" -ForegroundColor Green
}
